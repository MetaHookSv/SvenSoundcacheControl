#include <metahook.h>
#include <cvardef.h>
#include <net_api.h>
#include <demo_api.h>
#include "soundcache_control.h"

static_assert(METAHOOK_API_VERSION >= 109, "SvenSoundcacheControl requires MetaHook API 109 (ResolveGameSymbol)");

namespace
{
metahook_api_t*   g_API          = nullptr;
cl_enginefunc_t   g_Engine       = {};
cl_enginefunc_t*  g_ClientEngine = nullptr;
cl_exportfuncs_t  g_Exports      = {};
cvar_t*           g_AlwaysFlush  = nullptr;
SoundcacheControl g_Control;

using SoundMethod                                          = void(__fastcall*)(void*, int);
using FlushMethod                                          = void(__fastcall*)(void*, int, bool);
using LoadMethod                                           = bool(__fastcall*)(void*, int);
SoundMethod                             g_MapStarted       = nullptr;
SoundMethod                             g_ClearSoundArrays = nullptr;
FlushMethod                             g_FlushCache       = nullptr;
LoadMethod                              g_LoadSoundList    = nullptr;
hook_t*                                 g_MapHook          = nullptr;
hook_t*                                 g_FlushHook        = nullptr;
hook_t*                                 g_LoadHook         = nullptr;
decltype(cl_enginefunc_t::pfnClientCmd) g_ClientCmd        = nullptr;
bool                                    g_Loading          = false;

bool Enabled()
{
    return g_AlwaysFlush && g_AlwaysFlush->value != 0 &&
        !(g_Engine.pDemoAPI && g_Engine.pDemoAPI->IsPlayingback && g_Engine.pDemoAPI->IsPlayingback());
}

void* Resolve(void* base, const char* symbol, mh_gamesymbol_kind_t kind)
{
    void*      address = nullptr;
    const auto status  = g_API->ResolveGameSymbol(base, symbol, kind, &address);
    if (status != MH_GAMESYMBOL_OK)
        g_API->SysError("[SvenSoundcacheControl] Cannot resolve client symbol %s: %s (engine build %d).",
                        symbol, g_API->GetGameSymbolStatusString(status), g_API->GetEngineBuildnum());
    return address;
}

void __fastcall MapStarted(void* soundEngine, int dummy)
{
    net_status_t status = {};
    if (g_Engine.pNetAPI && g_Engine.pNetAPI->Status)
        g_Engine.pNetAPI->Status(&status);
    const bool  local  = status.remote_address.type == NA_LOOPBACK;
    const char* server = "";
    if (g_Engine.pNetAPI && g_Engine.pNetAPI->AdrToString)
        server = g_Engine.pNetAPI->AdrToString(&status.remote_address);
    const char* map = g_Engine.pfnGetLevelName();
    g_Control.BeginMap(map ? map : "", server ? server : "", local);

    if (Enabled())
    {
        // A queued dlfile from the previous load may have recreated the list.
        // Invalidate once per join, allowing the SDK's recovery join to use it.
        if (g_Control.InvalidateAtMapStart())
            g_FlushCache(soundEngine, dummy, true);
        g_ClearSoundArrays(soundEngine, dummy);
    }
    g_MapStarted(soundEngine, dummy);
}

void __fastcall FlushCache(void* soundEngine, int dummy, bool includingLocal)
{
    const auto action = g_Control.Flush(Enabled(), includingLocal, g_Loading);
    if (action != SoundcacheControl::FlushAction::Preserve)
        g_FlushCache(soundEngine, dummy, includingLocal || action == SoundcacheControl::FlushAction::ForceAll);
}

int ClientCmd(const char* command)
{
    if (Enabled() && !g_Control.IsLocal() && SoundcacheControl::IsRetryCommand(command))
    {
        if (!g_Control.RequestRecovery())
        {
            if (g_Control.WarnRecoveryFailure())
                g_Engine.Con_Printf("[SvenSoundcacheControl] Sound list download is still unavailable; waiting without another automatic retry. Check server downloads or set cl_soundcache_alwaysflush 0.\n");
            return 0;
        }
    }
    return g_ClientCmd(command);
}

bool __fastcall LoadSoundList(void* soundEngine, int dummy)
{
    // Only observe commands generated by this load, keeping the client's
    // existing command chain and the engine's asynchronous download behavior.
    if (g_Loading)
        return g_LoadSoundList(soundEngine, dummy);
    g_Loading                    = true;
    g_ClientCmd                  = g_ClientEngine->pfnClientCmd;
    g_ClientEngine->pfnClientCmd = ClientCmd;
    const bool loaded            = g_LoadSoundList(soundEngine, dummy);
    if (g_ClientEngine->pfnClientCmd == ClientCmd)
        g_ClientEngine->pfnClientCmd = g_ClientCmd;
    g_Loading = false;
    g_Control.FinishLoad(loaded);
    return loaded;
}

void HUD_Init()
{
    g_AlwaysFlush = g_Engine.pfnGetCvarPointer("cl_soundcache_alwaysflush");
    if (!g_AlwaysFlush)
        g_AlwaysFlush = g_Engine.pfnRegisterVariable("cl_soundcache_alwaysflush", "1", FCVAR_CLIENTDLL | FCVAR_ARCHIVE);
    g_Exports.HUD_Init();
}

void UninstallHooks()
{
    for (auto hook : {&g_LoadHook, &g_FlushHook, &g_MapHook})
    {
        if (*hook)
        {
            g_API->UnHook(*hook);
            *hook = nullptr;
        }
    }
}

void HUD_Shutdown()
{
    UninstallHooks();
    g_Control.Reset();
    g_AlwaysFlush = nullptr;
    g_Exports.HUD_Shutdown();
    g_ClientEngine = nullptr;
}
} // namespace

void IPluginsV4::Init(metahook_api_t* api, mh_interface_t*, mh_enginesave_t*)
{
    g_API = api;
}

void IPluginsV4::Shutdown()
{
    UninstallHooks();
}

void IPluginsV4::LoadEngine(cl_enginefunc_t* engine)
{
    g_Engine = *engine;
}

void IPluginsV4::LoadClient(cl_exportfuncs_t* exports)
{
    auto factory = g_API->GetClientFactory();
    if (!factory || !factory("SCClientDLL001", nullptr))
    {
        g_API->SysError("[SvenSoundcacheControl] This plugin requires the Sven Co-op client.");
        return;
    }
    auto base          = g_API->GetClientBase();
    g_MapStarted       = reinterpret_cast<SoundMethod>(Resolve(base, "CClient_SoundEngine_MapStarted", MH_GAMESYMBOL_KIND_FUNCTION));
    g_ClearSoundArrays = reinterpret_cast<SoundMethod>(Resolve(base, "CClient_SoundEngine_ClearSoundArrays", MH_GAMESYMBOL_KIND_FUNCTION));
    g_FlushCache       = reinterpret_cast<FlushMethod>(Resolve(base, "CClient_SoundEngine_FlushCache", MH_GAMESYMBOL_KIND_FUNCTION));
    g_LoadSoundList    = reinterpret_cast<LoadMethod>(Resolve(base, "CClient_SoundEngine_LoadSoundList", MH_GAMESYMBOL_KIND_FUNCTION));
    g_ClientEngine     = static_cast<cl_enginefunc_t*>(Resolve(base, "gEngfuncs", MH_GAMESYMBOL_KIND_GLOBAL));

    g_Exports             = *exports;
    exports->HUD_Init     = HUD_Init;
    exports->HUD_Shutdown = HUD_Shutdown;
    g_MapHook             = g_API->InlineHook(reinterpret_cast<void*>(g_MapStarted), reinterpret_cast<void*>(MapStarted), reinterpret_cast<void**>(&g_MapStarted));
    g_FlushHook           = g_API->InlineHook(reinterpret_cast<void*>(g_FlushCache), reinterpret_cast<void*>(FlushCache), reinterpret_cast<void**>(&g_FlushCache));
    g_LoadHook            = g_API->InlineHook(reinterpret_cast<void*>(g_LoadSoundList), reinterpret_cast<void*>(LoadSoundList), reinterpret_cast<void**>(&g_LoadSoundList));
    if (!g_MapHook || !g_FlushHook || !g_LoadHook)
        g_API->SysError("[SvenSoundcacheControl] Could not install soundcache hooks.");
}

void IPluginsV4::ExitGame(int)
{
    UninstallHooks();
}

const char* IPluginsV4::GetVersion()
{
    return "1.0.0";
}

EXPOSE_SINGLE_INTERFACE(IPluginsV4, IPluginsV4, METAHOOK_PLUGIN_API_VERSION_V4);
